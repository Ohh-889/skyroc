/** Demo 占位区号：按城市名稳定散列，免得为几十座城市维护一张表 */
export function toAreaCode(key: string) {
  const seed = [...key].reduce((sum, char) => sum + char.charCodeAt(0), 0);

  return `0${(seed % 800) + 100}`;
}
