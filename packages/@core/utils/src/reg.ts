/** 用户名：4-16 位中文、英文、数字、下划线、短横线 */
export const REG_USER_NAME = /^[\u4E00-\u9FA5a-zA-Z0-9_-]{4,16}$/;

/**
 * 中国大陆手机号：1 开头，第二位 3-9，共 11 位。
 *
 * 不再枚举号段白名单 —— 运营商放新号段时枚举式正则会立刻失效，而放宽到 `1[3-9]` 的漏判成本远低于误杀真实用户。真正的号码有效性交给短信验证码。
 */
export const REG_PHONE = /^1[3-9]\d{9}$/;

/**
 * 密码（宽松策略）：6-18 位字母、数字、下划线。
 *
 * ⚠️ 这条规则**禁止符号**，是一个偏弱的口令策略。仅在需要兼容存量账号体系时使用， 新项目请用 {@link REG_PWD_STRONG}。
 */
export const REG_PWD = /^\w{6,18}$/;

/** 密码（强策略）：8-32 位，必须同时包含大小写字母与数字，允许符号 */
export const REG_PWD_STRONG = /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)\S{8,32}$/;

/** 邮箱 */
export const REG_EMAIL = /^\w+([-+.]\w+)*@\w+([-.]\w+)*\.\w+([-.]\w+)*$/;

/** 六位数字验证码 */
export const REG_CODE_SIX = /^\d{6}$/;

/** 四位数字验证码 */
export const REG_CODE_FOUR = /^\d{4}$/;

/**
 * HTTP(S) / 协议相对 URL。
 *
 * 各段字符集互不重叠、量词不嵌套，失配时不会产生指数级回溯（原版把 `\w` 同时放进 相邻两个字符类里，是典型的 ReDoS 形状）。
 */
export const REG_URL = /^(https?:\/\/|\/\/)?([\w-]+\.)+[a-zA-Z]{2,}(:\d{1,5})?(\/[^\s?#]*)?(\?[^\s#]*)?(#\S*)?$/;
